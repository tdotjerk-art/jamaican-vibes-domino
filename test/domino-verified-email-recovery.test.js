'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {createSqliteWallet}=require('../domino-wallet-sqlite');
test('verified email registration blocks unverified wallet and protects code replay across database reopen',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'jv-email-account-'));
 const filename=path.join(dir,'wallet.sqlite');
 const wallet=createSqliteWallet(filename,{verifiedEmailRequired:true});
 t.after(()=>{wallet.close();fs.rmSync(dir,{recursive:true,force:true})});
 assert.throws(()=>wallet.createAccount('MissingEmail','127.0.0.1'),/email address/);
 const account=wallet.createAccount('VerifiedPlayer','127.0.0.1',' Player@example.com ');
 assert.equal(account.email,'player@example.com');
 assert.match(account.emailCode,/^[a-f0-9]{48}$/);
 assert.throws(()=>wallet.authenticate(account.id,account.token),/Email verification required/);
 assert.throws(()=>wallet.verifyRegistrationEmail(account.id,'0'.repeat(48)),/Invalid or expired/);
 assert.throws(()=>wallet.createAccount('CopyEmail','198.51.100.1','PLAYER@example.com'),/already registered/i);
 assert.equal(wallet.balance(account.id),100);
 const verified=wallet.verifyRegistrationEmail(account.id,account.emailCode);
 assert.equal(verified.id,account.id);
 assert.equal(verified.balance,100);
 assert.notEqual(verified.token,account.token);
 assert.throws(()=>wallet.verifyRegistrationEmail(account.id,account.emailCode),/Invalid or expired/);
 assert.throws(()=>wallet.authenticate(account.id,account.token),/credentials/);
 assert.equal(wallet.authenticate(account.id,verified.token).balance,100);
 const resumed=createSqliteWallet(filename,{verifiedEmailRequired:true});
 assert.equal(resumed.authenticate(account.id,verified.token).balance,100);
 resumed.close();
});
test('verified recovery is single use, email-bound and preserves wallet balance',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'jv-email-recovery-'));
 const wallet=createSqliteWallet(path.join(dir,'wallet.sqlite'),{verifiedEmailRequired:true});
 t.after(()=>{wallet.close();fs.rmSync(dir,{recursive:true,force:true})});
 const account=wallet.createAccount('Recoverable','127.0.0.2','recover@example.com');
 const verified=wallet.verifyRegistrationEmail(account.id,account.emailCode);
 wallet.enter(account.id,'public','before-recovery');
 assert.equal(wallet.balance(account.id),90);
 assert.equal(wallet.requestEmailRecovery('nobody@example.com'),null);
 const request=wallet.requestEmailRecovery('RECOVER@example.com');
 assert.match(request.code,/^[a-f0-9]{48}$/);
 assert.equal(wallet.requestEmailRecovery('recover@example.com'),null,'Email cooldown');
 assert.throws(()=>wallet.completeEmailRecovery('other@example.com',request.code),/Invalid or expired/);
 assert.throws(()=>wallet.completeEmailRecovery('recover@example.com','0'.repeat(48)),/Invalid or expired/);
 const recovered=wallet.completeEmailRecovery('recover@example.com',request.code);
 assert.equal(recovered.id,account.id);
 assert.equal(recovered.balance,90);
 assert.throws(()=>wallet.authenticate(account.id,verified.token),/credentials/);
 assert.equal(wallet.authenticate(account.id,recovered.token).balance,90);
 assert.throws(()=>wallet.completeEmailRecovery('recover@example.com',request.code),/Invalid or expired/);
});
test('expired registration and recovery challenges reject without altering identity',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'jv-email-expiry-'));
 const wallet=createSqliteWallet(path.join(dir,'wallet.sqlite'),{verifiedEmailRequired:true});
 t.after(()=>{wallet.close();fs.rmSync(dir,{recursive:true,force:true})});
 const created=wallet.createAccount('Expiry','127.0.0.3','expires@example.com');
 assert.throws(()=>wallet.verifyRegistrationEmail(created.id,created.emailCode,Date.now()+16*60000),/Invalid or expired/);
 const valid=wallet.verifyRegistrationEmail(created.id,created.emailCode);
 const requestedAt=Date.now();
 const r=wallet.requestEmailRecovery('expires@example.com',requestedAt);
 assert.throws(()=>wallet.completeEmailRecovery('expires@example.com',r.code,requestedAt+16*60000),/Invalid or expired/);
 assert.equal(wallet.authenticate(created.id,valid.token).balance,100);
});

test('verification resend is email-bound, limited daily and limit survives restart',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'jv-email-limit-'));
 const filename=path.join(dir,'wallet.sqlite');
 const wallet=createSqliteWallet(filename,{verifiedEmailRequired:true});
 t.after(()=>{wallet.close();fs.rmSync(dir,{recursive:true,force:true})});
 const created=wallet.createAccount('QuotaOwner','127.0.0.4','quota@example.com');
 const futureMidnight=Date.UTC(new Date().getUTCFullYear(),new Date().getUTCMonth(),new Date().getUTCDate()+1);
 const base=futureMidnight+2*60*60000;
 assert.throws(()=>wallet.resendRegistrationEmail(created.id,'other@example.com',base),/not found/);
 let latest=null;
 for(let n=0;n<5;n++){
   latest=wallet.resendRegistrationEmail(created.id,'quota@example.com',base+n*16*60000);
   assert.match(latest.code,/^[a-f0-9]{48}$/);
 }
 assert.throws(()=>wallet.resendRegistrationEmail(created.id,'quota@example.com',base+5*16*60000),/Daily email request limit/);
 assert.throws(()=>wallet.verifyRegistrationEmail(created.id,created.emailCode,base+6*16*60000),/Invalid or expired/);
 const reopened=createSqliteWallet(filename,{verifiedEmailRequired:true});
 assert.throws(()=>reopened.resendRegistrationEmail(created.id,'quota@example.com',base+5*16*60000),/Daily email request limit/);
 reopened.close();
});
